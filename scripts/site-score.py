#!/usr/bin/env python3
"""Score our browser against real Chrome on a list of real sites; write docs/site-score.md, worst first.

    python3 scripts/site-score.py [--drive /tmp/aios-lite/<fork>/aios-web-pane-drive] [--out /tmp/site-score]
                                  [--only substring] [--jobs 2] [--md docs/site-score.md]

Each URL runs through ~/.avalon/briefs/refdiff.py (similarity of the first screen, 0-100). We also record our wall
time and any script/handler errors the drive printed, so a low score can be told apart from a crash or a timeout.
"""
import argparse, concurrent.futures as cf, hashlib, os, re, subprocess, sys, time

URLS = """
https://en.wikipedia.org/wiki/Moon_landing
https://en.wikipedia.org/wiki/Moon_landing?useskin=vector
https://en.wikipedia.org/wiki/Moon_landing?useskin=vector-2022
https://en.wikipedia.org/wiki/Main_Page
https://en.wikipedia.org/wiki/Main_Page?useskin=vector
https://en.wikipedia.org/w/index.php?search=moon+landing&ns0=1
https://en.wikipedia.org/w/index.php?search=moon+landing&ns0=1&useskin=vector
https://en.wikipedia.org/wiki/Category:Apollo_program
https://en.wikipedia.org/wiki/Category:Apollo_program?useskin=vector
https://news.ycombinator.com/
https://news.ycombinator.com/item?id=1
https://lobste.rs/
https://example.com/
https://www.gnu.org/
https://www.gnu.org/philosophy/free-sw.html
https://www.gnu.org/software/gcc/
https://www.w3.org/TR/css-flexbox-1/
https://www.w3.org/TR/html52/
https://www.w3.org/
https://doc.rust-lang.org/book/ch01-01-installation.html
https://docs.python.org/3/tutorial/index.html
https://docs.python.org/3/library/functions.html
https://text.npr.org/
https://lite.cnn.com/
https://www.bbc.com/news
https://apnews.com/
https://www.theguardian.com/international
https://stackoverflow.com/questions/11227809
https://old.reddit.com/
https://old.reddit.com/r/programming/
https://github.com/torvalds/linux
https://github.com/rust-lang/rust/blob/master/README.md
https://www.npmjs.com/package/left-pad
https://developer.mozilla.org/en-US/docs/Web/HTML
https://developer.mozilla.org/en-US/docs/Web/CSS/flex
https://www.rust-lang.org/
https://www.python.org/
https://go.dev/
https://news.ycombinator.com/newest
https://motherfuckingwebsite.com/
""".split()

ap = argparse.ArgumentParser()
ap.add_argument("--drive", default="")
ap.add_argument("--out", default="/tmp/site-score")
ap.add_argument("--only", default="")
ap.add_argument("--jobs", type=int, default=2)
ap.add_argument("--md", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "site-score.md"))
a = ap.parse_args()
if not a.drive:
    fork = os.path.basename(os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")))
    a.drive = f"/tmp/aios-lite/{fork}/aios-web-pane-drive"
refdiff = os.path.expanduser("~/.avalon/briefs/refdiff.py")

def one(url):
    d = f"{a.out}/{hashlib.md5(url.encode()).hexdigest()[:8]}"
    t = time.time()
    try:
        r = subprocess.run([sys.executable, refdiff, url, "--drive", a.drive, "--out", d],
                           capture_output=True, text=True, timeout=400)
        text = r.stdout + r.stderr
    except subprocess.TimeoutExpired:
        return (url, None, 400.0, "timeout", d)
    wall = time.time() - t
    m = re.search(r"similarity of the first screen: ([\d.]+)", text)
    errs = sorted({l.strip()[:80] for l in text.splitlines()
                   if re.search(r"handler failed|script error|Traceback|Error", l)})[:2]
    lm = re.search(r"laid out[^\n]*?([\d.]+) ?ms", text)
    return (url, float(m.group(1)) if m else None, wall, "; ".join(errs) or ("" if m else "no frame"), d)

urls = [u for u in URLS if a.only in u]
with cf.ThreadPoolExecutor(a.jobs) as ex:
    rows = list(ex.map(one, urls))
rows.sort(key=lambda r: (-1 if r[1] is None else r[1]))
os.makedirs(os.path.dirname(os.path.abspath(a.md)), exist_ok=True)
with open(a.md, "w") as f:
    f.write("# Site score vs Chrome\n\nGenerated by `scripts/site-score.py` (first-screen similarity, 0-100, higher is closer; "
            "time is our drive plus Chrome wall time). Worst first.\n\n| similarity | time (s) | URL | errors |\n|---|---|---|---|\n")
    for url, s, w, e, d in rows:
        f.write(f"| {'-' if s is None else f'{s:.1f}'} | {w:.0f} | {url} | {e.replace('|', '/')} |\n")
print(open(a.md).read())
