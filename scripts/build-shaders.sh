#!/usr/bin/env bash
# Compiles the Vulkan compute shaders to SPIR-V and writes the words into a
# header. Run it when src/compute/shaders/*.comp changes.
#
# The generated header is CHECKED IN. A machine building this OS need not have
# a shader compiler on it, and a Vulkan backend that quietly comes up with no
# kernels on such a machine would look exactly like one that works.
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)

compiler=$(command -v glslangValidator || command -v glslc || true)
[ -n "$compiler" ] || { echo "no SPIR-V compiler (glslangValidator or glslc) on this machine" >&2; exit 1; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
version=$("$compiler" --version 2>&1 | head -1 | tr -d '\r')

# name -> symbol. Each shader becomes one header beside its source.
compile_one() {
  local name=$1 symbol=$2
  local src=$here/src/compute/shaders/$name.comp
  local out=$here/src/compute/shaders/${name}_spv.h
  case "$compiler" in
    *glslangValidator) "$compiler" -V "$src" -o "$tmp/$name.spv" > /dev/null ;;
    *glslc)            "$compiler" -fshader-stage=compute "$src" -o "$tmp/$name.spv" > /dev/null ;;
  esac
  {
    echo "#pragma once"
    echo "// GENERATED by scripts/build-shaders.sh from src/compute/shaders/$name.comp."
    echo "// Do not edit this file: edit the shader and run the script again."
    echo "// Compiled by: $version"
    echo "#include <cstdint>"
    echo "namespace aios::compute {"
    echo "inline constexpr uint32_t k${symbol}Spv[] = {"
    od -An -tx4 -v "$tmp/$name.spv" | awk '{ for (i = 1; i <= NF; i++) printf "0x%s,", $i; print "" }'
    echo "};"
    echo "inline constexpr uint32_t k${symbol}SpvWords = sizeof(k${symbol}Spv) / sizeof(uint32_t);"
    echo "}  // namespace aios::compute"
  } > "$out"
  echo "wrote $out ($(wc -c < "$tmp/$name.spv") bytes of SPIR-V)"
}

compile_one aios_compute AiosCompute
compile_one aios_scene   AiosScene
