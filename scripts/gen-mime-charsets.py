#!/usr/bin/env python3
"""Regenerates src/net/mime_charsets.inc: the 0x80..0xFF half of the single-byte charsets mail
still uses, taken from Python's codec tables. Run it from the repository root:
    python3 scripts/gen-mime-charsets.py > src/net/mime_charsets.inc
The product has no Python in it; this only builds a table once, and the table is checked in."""
names = [("cp1250", "windows-1250"), ("cp1251", "windows-1251"), ("cp1252", "windows-1252"),
         ("koi8_r", "koi8-r"), ("iso8859_2", "iso-8859-2"), ("iso8859_15", "iso-8859-15")]
print("// Generated by scripts/gen-mime-charsets.py (0x80..0xFF -> Unicode); 0xFFFD where the charset has no character.")
print("// Do not edit by hand.")
for py, label in names:
    vals = []
    for b in range(0x80, 0x100):
        try:
            vals.append(ord(bytes([b]).decode(py)))
        except Exception:
            vals.append(0xFFFD)
    print("static const uint16_t kCs_%s[128] = {" % py.upper())
    for i in range(0, 128, 8):
        print("  " + ", ".join("0x%04X" % v for v in vals[i:i + 8]) + ",")
    print("};")
