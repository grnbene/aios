#!/usr/bin/env python3
"""Generate src/userland/unicode_classes.inc: the code point ranges of the
Unicode letter (L*) and number (N*) categories the byte-level BPE tokenizer's
pre-tokenizer splits on.

    scripts/gen-unicode-classes.py > src/userland/unicode_classes.inc
"""
import sys, unicodedata

def ranges(prefix):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        hit = unicodedata.category(chr(cp)).startswith(prefix)
        if hit and start is None:
            start = cp
        if not hit and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

print("// Generated by scripts/gen-unicode-classes.py (Unicode %s); do not edit." % unicodedata.unidata_version)
for name, pre in (("kLetters", "L"), ("kNumbers", "N")):
    r = ranges(pre)
    print("static const uint32_t %s[][2] = {" % name)
    for i in range(0, len(r), 6):
        print("  " + " ".join("{0x%X,0x%X}," % x for x in r[i:i+6]))
    print("};")
