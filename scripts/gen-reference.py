#!/usr/bin/env python3
"""Generate docs/reference.md and docs/tools.md from the source itself.

    scripts/gen-reference.py            write both files
    scripts/gen-reference.py --check    exit 1 if either file is out of date

The command reference is read from the console's dispatcher (cli/commands.cpp):
every command name and alias, the handler it reaches, the one-line help the
console prints, every subcommand the handler tests for, and every usage line it
prints when it is called wrongly. The tools reference is read from CMakeLists.txt
and each program's own header comment. cli/command_aliases.inc, which `man`
reads, comes from the same dispatcher. Nothing here is written by hand, so it
cannot drift from the code: rerun it after changing a command or a tool.
"""
import os, re, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CMDS = os.path.join(HERE, "cli", "commands.cpp")


def read(p):
    with open(p, encoding="utf-8", errors="replace") as f:
        return f.read()


def line_of(text, pos):
    return text.count("\n", 0, pos) + 1


def unescape(s):
    return s.replace('\\"', '"').replace("\\n", " ").replace("\\t", " ").strip()


def help_lines(src):
    """name -> (section, usage, description) from print_help."""
    m = re.search(r"void print_help\(Out& o\) \{(.*?)\n\}", src, re.S)
    out, section = {}, ""
    if not m:
        return out
    for ln in m.group(1).split("\n"):
        sec = re.search(r'style\(Bold\(\)\) << "([^"]+)"', ln)
        if sec:
            section = sec.group(1).strip()
        h = re.search(r'W\{\d+\} << "([^"]+)" << o\.style\(Reset\(\)\) << "([^"]*)', ln)
        if h:
            usage, desc = unescape(h.group(1)), unescape(h.group(2))
            # " | " separates commands sharing a line ("reboot | poweroff",
            # "chain | btc ..."); a bare | separates subcommands. As `man` reads it.
            names = []
            for alt in usage.split(" | "):
                w = re.split(r"[ |]", alt.strip())
                if w and w[0] and w[0] not in names:
                    names.append(w[0])
            for name in names:
                out.setdefault(name, []).append((section, usage, desc))
    return out


def dispatcher(src):
    """[(names, target, line)] in dispatch order."""
    rows = []
    for m in re.finditer(r'(?:if|else if) \(((?:cmd == "[a-z0-9_-]+"(?: \|\| )?)+)\)\s*(.{0,160})', src):
        names = re.findall(r'cmd == "([a-z0-9_-]+)"', m.group(1))
        body = m.group(2)
        t = re.search(r"\b((?:cmd_|[a-z_]+_command\b)[a-z0-9_]*)\s*\(", body)
        target = t.group(1) if t else "(inline)"
        rows.append((names, target, line_of(src, m.start())))
    return rows


def functions(src):
    """handler name -> (start line, body)."""
    out = {}
    for m in re.finditer(r"\n(?:static )?(?:void|Result<[^>]+>|std::string|bool|int) ((?:cmd_|[a-z_]+_command)[a-z0-9_]*)\([^)]*\)\s*\{", src):
        start = m.end()
        depth, i = 1, start
        while i < len(src) and depth:
            c = src[i]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
            elif c == '"':
                i += 1
                while i < len(src) and src[i] != '"':
                    i += 2 if src[i] == "\\" else 1
            i += 1
        out.setdefault(m.group(1), (line_of(src, m.start() + 1), src[start:i]))
    return out


def gen_reference():
    src = read(CMDS)
    helps = help_lines(src)
    funcs = functions(src)
    seen = set()
    out = ["# Command reference", "",
           "Generated by `scripts/gen-reference.py` from `cli/commands.cpp`; do not edit by hand.",
           "Every command the console dispatches, the handler it reaches, the help line it prints,",
           "the subcommands the handler tests for, and the usage lines it prints when called wrongly.",
           "For how to use them, see the guides listed in the README.", ""]
    rows = dispatcher(src)
    total_subs = 0
    body = []
    for names, target, ln in rows:
        key = names[0]
        if key in seen:
            continue
        seen.add(key)
        body.append(f"## `{key}`")
        body.append("")
        if len(names) > 1:
            body.append("Also: " + ", ".join(f"`{n}`" for n in names[1:]))
            body.append("")
        loc = f"`cli/commands.cpp:{ln}`"
        if target in funcs:
            loc += f" → `{target}` (`cli/commands.cpp:{funcs[target][0]}`)"
        elif target != "(inline)":
            loc += f" → `{target}` (in `cli/`)"
        body.append("Dispatched at " + loc + ".")
        body.append("")
        for n in names:
            for section, usage, desc in helps.get(n, []):
                body.append(f"- **{usage}**: {desc}" + (f" *({section.title()})*" if section else ""))
        if any(helps.get(n) for n in names):
            body.append("")
        if target in funcs:
            fb = funcs[target][1]
            subs = sorted(set(re.findall(r'sub == "([a-z0-9_-]+)"', fb)))
            if subs:
                total_subs += len(subs)
                body.append("Subcommands: " + " ".join(f"`{s}`" for s in subs))
                body.append("")
            usages = []
            for u in re.findall(r'fail\(Status::Invalid,\s*"((?:[^"\\]|\\.)*)"', fb):
                u = unescape(u)
                if any(u.startswith(n + " ") or u == n for n in names) and u not in usages:
                    usages.append(u)
            if usages:
                body.append("```")
                for u in usages:
                    for part in u.split(" | ") if len(u) > 110 else [u]:
                        body.append(part)
                body.append("```")
                body.append("")
    shell = sorted(set(re.findall(r'(?:cmd|c|name|w) == "([a-z0-9_-]+)"', read(os.path.join(HERE, "cli", "shell.cpp")))))
    out.append(f"{len(seen)} commands, {total_subs} subcommands, and {len(shell)} familiar shell commands.")
    out.append("")
    out.append("The familiar shell (`cli/shell.cpp`, see docs/console.md): " + " ".join(f"`{n}`" for n in shell))
    out.append("")
    out.append("Commands: " + " ".join(f"[`{n}`](#{n})" for n in sorted(seen)))
    out.append("")
    return "\n".join(out + body).rstrip() + "\n"


def gen_aliases():
    """cli/command_aliases.inc: alias -> the command it names, for `man`."""
    seen, out = set(), ["// Generated by scripts/gen-reference.py from cli/commands.cpp; do not edit by hand.",
                         "// Each alias the dispatcher accepts, and the command it names."]
    for names, target, ln in dispatcher(read(CMDS)):
        if names[0] in seen:
            continue
        seen.add(names[0])
        for alias in names[1:]:
            out.append('{"%s", "%s"},' % (alias, names[0]))
    return "\n".join(out) + "\n"


def gen_tools():
    cm = read(os.path.join(HERE, "CMakeLists.txt"))
    tests = {}
    for m in re.finditer(r"add_test\(NAME (\S+) COMMAND ([^\s)]+)", cm):
        tests.setdefault(m.group(2).replace("${CMAKE_BINARY_DIR}/", ""), []).append(m.group(1))
    out = ["# Programs the build produces", "",
           "Generated by `scripts/gen-reference.py` from `CMakeLists.txt` and each program's own header",
           "comment; do not edit by hand. The drives exercise a subsystem the way an operator does; the",
           "checks assert on it; the benches measure it. `ctest` runs the ones registered as tests.", "",
           "| program | source | registered test | what it is |", "|---|---|---|---|"]
    # Targets inside if(FALSE)/if(OFF) blocks are never built, so a plain
    # regex over the whole file would advertise them as real programs. Walk the
    # file line by line instead, tracking whether we are inside a disabled block.
    cm_lines = cm.split("\n")
    disabled = 0
    targets = []
    for ln in cm_lines:
        stripped = ln.strip()
        mcond = re.match(r"if\s*\(\s*([A-Za-z0-9_.\"! ]+?)\s*\)", stripped)
        if mcond:
            cond = mcond.group(1).strip().strip('"')
            if cond in ("FALSE", "OFF", "0"):
                disabled += 1
        elif stripped.startswith("endif"):
            disabled = max(0, disabled - 1)
        m = re.match(r"add_executable\(([A-Za-z0-9_-]+)\s+([^)]+)\)", stripped)
        if m:
            targets.append((m.group(1), m.group(2).split(), disabled > 0))
    for name, srcs, not_built in targets:
        if name == "aios-cli":
            shown = "aios"
        else:
            shown = name
        first = next((s for s in srcs if s.endswith((".cpp", ".c"))), "")
        desc = ""
        p = os.path.join(HERE, first)
        if first and os.path.exists(p):
            # A program's description is its file header: a column-0 comment run that a
            # blank line or a #directive follows. A run that sits directly on a declaration
            # (a helper struct's comment) describes that declaration, not the program.
            src_lines = read(p).split("\n")[:60]
            lines, run, i = [], [], 0
            while i < len(src_lines):
                ln = src_lines[i]
                s = ln.strip()
                if ln.startswith(("//", "/*", " *")):
                    if not s.startswith(("// SPDX", "//#")):
                        t = re.sub(r"^(//+|/\*+|\*+/?)\s?", "", s).rstrip("*/ ").strip()
                        if t:
                            run.append(t)
                    i += 1
                    continue
                if run and (not s or s.startswith("#")):
                    lines = run
                    break
                run = []
                if s and not s.startswith(("#", "using ", "namespace ")):
                    break   # real code reached with no header seen
                i += 1
            desc = re.sub(r"\s+", " ", " ".join(lines))
            if len(desc) > 260:
                desc = desc[:257].rsplit(" ", 1)[0] + " …"
        t = ", ".join(f"`{x}`" for x in tests.get(name, []))
        if not_built:
            note = "**not built** (disabled in `CMakeLists.txt`)"
            if not desc:
                desc = note
            else:
                desc = f"{desc} -- {note}"
        out.append(f"| `{shown}` | `{first}` | {t} | {desc.replace('|', '/') or '(no header comment)'} |")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv
    stale = False
    for rel, text in (("docs/reference.md", gen_reference()), ("docs/tools.md", gen_tools()),
                      ("cli/command_aliases.inc", gen_aliases())):
        p = os.path.join(HERE, rel)
        old = read(p) if os.path.exists(p) else None
        if old == text:
            continue
        if check:
            print(f"{rel} is out of date: run scripts/gen-reference.py")
            stale = True
        else:
            with open(p, "w", encoding="utf-8") as f:
                f.write(text)
            print(f"wrote {rel}")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
