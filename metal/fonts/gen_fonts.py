#!/usr/bin/env python3
"""Rasterize the UI typefaces into anti-aliased glyph atlases for the bare-metal kernel.

    python3 metal/fonts/gen_fonts.py > metal/arm64/aa_fonts.inc

Each face becomes 8-bit coverage bitmaps for printable ASCII plus metrics:
per-glyph bitmap offset from the pen/baseline and an advance in 1/64 px, so
text is laid out with fractional advances (as macOS does) instead of on a
fixed 8 px grid. Fonts: Inter and JetBrains Mono, both SIL OFL 1.1 (licence
files beside this script).
"""
import os
import sys
from PIL import ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
# name, file, pixel size, baseline offset from the line top
FACES = [
    ("body",     "Inter-Regular.ttf",         13, 12),
    ("medium",   "Inter-Medium.ttf",          13, 12),
    ("semibold", "Inter-SemiBold.ttf",        13, 12),
    ("small",    "Inter-Medium.ttf",          11, 11),
    ("large",    "InterDisplay-SemiBold.ttf", 17, 14),
    ("mono",     "JetBrainsMono-Regular.ttf", 12, 12),
]
FIRST, LAST = 32, 126


def face(name, fname, px, baseline):
    font = ImageFont.truetype(os.path.join(HERE, fname), px, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv64 = int(round(font.getlength(ch) * 64))
        mask, offset = font.getmask2(ch, mode="L")
        w, h = mask.size
        # getmask2 offset is from the layout origin (top of the ascent box)
        xoff, yoff = offset[0], offset[1] - ascent
        start = len(bitmap)
        if w and h:
            data = bytes(mask)
            for row in range(h):
                bitmap += data[row * w:(row + 1) * w]
        glyphs.append((xoff, yoff, w, h, adv64, start))
    out = [f"const uint8_t kAa_{name}_bits[] = {{"]
    for i in range(0, len(bitmap), 24):
        out.append("  " + ",".join(str(b) for b in bitmap[i:i + 24]) + ",")
    out.append("};")
    out.append(f"const AaGlyph kAa_{name}_glyphs[] = {{")
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"const AaFont kAaFont_{name} = {{kAa_{name}_glyphs, kAa_{name}_bits, {FIRST}, {LAST - FIRST + 1}, "
               f"{baseline}, {ascent + descent}}};")
    return "\n".join(out)


def main():
    print("/* Generated by metal/fonts/gen_fonts.py - do not edit. Inter / JetBrains Mono, SIL OFL 1.1. */")
    for f in FACES:
        print(face(*f))
        print()


if __name__ == "__main__":
    main()
